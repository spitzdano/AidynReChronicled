#!/usr/bin/env python3
"""Reads descriptions.md (the bestiary's own words: written for the port, not copied from anywhere) and writes
src/game/bestiary_text.h: for each creature the name the game's table gives it, the name shown, its family and its note,
and which ones are one-off enemies (bosses: one fight shows everything).
usage: python3 -I tools/bestiary/make_text.py"""
import re
from pathlib import Path

root = Path(__file__).resolve().parents[2]
src = (root / "tools/bestiary/descriptions.md").read_text()
# the game's names for the ones it names differently from how they're written here
SHOWN = {"Assim": "Drakeguardian Assim", "Behrooz": "Drakeguardian Behrooz", "Golnar": "Drakeguardian Golnar",
         "Ksathra": "Drakeguardian Ksathra", "Mehrdad": "Drakeguardian Mehrdad", "Nasim": "Drakeguardian Nasim",
         "Shatrevar": "Drakeguardian Shatrevar", "Sheridan": "Prince Sheridan", "Lizard Man Sgt": "Lizard Man Sergeant"}
BOSSES = {"Shamsuk", "Lugash", "Marquis", "Pochanargat", "Sheridan", "Shadow", "Kitarak", "Firelord", "Assim", "Behrooz",
          "Golnar", "Ksathra", "Mehrdad", "Nasim", "Shatrevar", "Dougal"}
entries, family = [], ""
for line in src.splitlines():
    m = re.match(r"## (.+)", line)
    if m:
        family = m.group(1).strip()
        continue
    if family in ("", "For you to decide") or family.startswith("People"):
        continue
    m = re.match(r"- \*\*(.+?)\*\*:\s*(.+)", line)
    if not m:
        continue
    names, text = m.group(1), m.group(2)
    text = re.sub(r"\s*\[\?[^\]]*\]", "", text).strip()  # the drafts' open questions are not for the game
    for n in re.split(r"\s*/\s*", names):
        n = re.sub(r"\s*\(file name: ([^)]+)\)", lambda k: "@" + k.group(1), n).strip()
        game = n.split("@")[1] if "@" in n else n
        if game.startswith("Drakeguardian "):  # the game's table names them by the first name only
            game = game[len("Drakeguardian "):]
        shown = n.split("@")[0].strip() if "@" in n else SHOWN.get(game, game)
        entries.append((game, shown, family, text, game in BOSSES))
out = ["// Generated by tools/bestiary/make_text.py from tools/bestiary/descriptions.md. Do not edit.", "#pragma once", "",
       "namespace aidyn::bestiary_text {", "struct Entry { const char* game; const char* shown; const char* family; const char* text; bool boss; };",
       "inline constexpr Entry kEntries[] = {"]
esc = lambda t: t.replace("\\", "\\\\").replace('"', '\\"')
for g, s, f, t, b in entries:
    out.append(f'    {{ "{esc(g)}", "{esc(s)}", "{esc(f)}", "{esc(t)}", {"true" if b else "false"} }},')
out += ["};", "}  // namespace aidyn::bestiary_text", ""]
(root / "src/game/bestiary_text.h").write_text("\n".join(out))
print(len(entries), "entries")
