#!/usr/bin/env python3
"""action_shops.py: Action Edition's shop stock, for the Original's "Better shops" rule (src/game/patches.cpp, "Better
shops").

    tools/data/action_shops.py [--rom <Action Edition ROM>] [--original baserom.z64]

Action Edition (MDoulos's mod) restocks the game's 75 shops to their themes; the original's are thin. MDoulos agreed
(2026-10-29) to its shop stock becoming ReChronicled's base, with credit. Each shop in the ROM's shop table (shopdb, ROM
0x1FD31B0: a count, then 75 records of 108 bytes: the shopkeeper, 20 items each with 3 price bytes, 3 more items) is
read from the Action Edition ROM and written to src/game/action_shops.h, record for record. Checked against the
original: the same 75 shops in the same order with the same shopkeepers, and every item they stock is one the original
has (its armour, weapon and spell lists and its item ID table), so the records fit the original's game as they are.
Generated: re-run this (then rebuild the game), never edit the header.
"""
import argparse
import struct
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[2]
SHOPS, RECORD = 0x1FD31B0, 108
OUT = PROJECT / "src/game/action_shops.h"


def table(rom):
    count = rom[SHOPS]
    return count, [rom[SHOPS + 4 + RECORD * i:SHOPS + 4 + RECORD * (i + 1)] for i in range(count)]


def items(record):
    return [record[2 + 5 * j] | record[3 + 5 * j] << 8 for j in range(20)] + \
           [record[102 + 2 * j] | record[103 + 2 * j] << 8 for j in range(3)]


def check(original, action):
    """Same shops and shopkeepers, and every stocked item one the original has."""
    n, orig = table(original)
    m, act = table(action)
    if n != m:
        raise SystemExit(f"action_shops.py: {m} shops in Action Edition, {n} in the original")
    armour, weapons, spells = original[0xE1850:0xE1850 + 0x44], original[0xE3790:0xE3790 + 0x69], original[0xE3740:0xE3740 + 0x40]
    misc = set(struct.unpack(">200H", original[0xE3590:0xE3590 + 0x190]))

    def known(i):
        kind, low = i >> 8, i & 0xFF
        if kind in (5, 6):
            return low in armour
        if kind == 7:
            return low in weapons
        if kind == 3:
            return low in spells
        if kind == 16:
            return low < 17
        return i in misc
    for k, (o, a) in enumerate(zip(orig, act)):
        if o[:2] != a[:2]:
            raise SystemExit(f"action_shops.py: shop {k} has another shopkeeper in Action Edition")
        bad = [i for i in items(a) if i and not known(i)]
        if bad:
            raise SystemExit(f"action_shops.py: shop {k} stocks items the original doesn't have: {[hex(i) for i in bad]}")
    return act


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    data = Path.home() / ".local/share/AidynReChronicled"
    ap.add_argument("--rom", type=Path, default=data / "aidyn.n64.us.1.0.action-edition.z64")
    ap.add_argument("--original", type=Path, default=PROJECT / "baserom.z64")
    args = ap.parse_args()
    records = check(args.original.read_bytes(), args.rom.read_bytes())
    lines = ["// Generated by tools/data/action_shops.py from the Action Edition ROM: never edit, re-run it.",
             "// Action Edition's shop records (MDoulos's mod, used with his agreement), as the ROM's shop table has them:",
             "// the shopkeeper, 20 items each with 3 price bytes (the middle one the price multiplier), 3 more items.",
             "#pragma once", "#include <cstdint>", "",
             f"namespace aidyn::action_shops {{",
             f"inline constexpr int kShops = {len(records)}, kRecord = {RECORD};",
             f"inline constexpr uint8_t kRecords[{len(records)}][{RECORD}] = {{"]
    for r in records:
        lines.append("    { " + ", ".join(f"0x{b:02x}" for b in r) + " },")
    lines += ["};", "}", ""]
    OUT.write_text("\n".join(lines))
    print(f"action_shops.py: {len(records)} shops -> {OUT.relative_to(PROJECT)}")


if __name__ == "__main__":
    main()
